/// Shop behind a merchant logo asset, or `null` for anything outside
/// `assets/merchants/`.
String? merchantNameFor(String asset) {
  if (!asset.startsWith(merchantAssetDir)) return null;
  final file = asset.substring(merchantAssetDir.length);
  final stem = file.replaceAll(RegExp(r'\.(png|jpg|jpeg|svg)$'), '').replaceAll(' copy', '');
  final known = _names[stem];
  if (known != null) return known;
  return stem
      .replaceAll(_tail, '')
      .split(_separators)
      .where((w) => w.isNotEmpty)
      .map((w) => w[0].toUpperCase() + w.substring(1))
      .join(' ');
}
